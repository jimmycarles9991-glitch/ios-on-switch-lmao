"""What a build from before the driver left raw/ printed, in today's names, so its pulls and runs compare with new ones.

renamed.tsv is generated by the rename tool from the rules it renamed the tree by (do not edit it): `token` rows are
identifiers the device prints whole (Objective-C classes, selectors, HW Test metric keys), `regex` rows the log tag,
refusal keys and domains, the path kind, the rates line and the test and check ids, and `literal` rows a new
literal's old spelling, for a log predicate that has to find both.
"""

import functools
import re
from pathlib import Path

TABLE = Path(__file__).with_name('renamed.tsv')
WORD = r'(?<![A-Za-z0-9_]){}(?![A-Za-z0-9_])'


@functools.cache
def _table() -> tuple[dict[str, str], re.Pattern, list[tuple[re.Pattern, str]], list[tuple[str, str]]]:
    tokens, regexes, literals = {}, [], []
    for line in TABLE.read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        kind, old, new = line.split('\t')[:3]
        if kind == 'token':
            tokens[old] = new
        elif kind == 'regex':
            regexes.append((re.compile(old), new))
        elif kind == 'literal':
            literals.append((new, old))
    names = '|'.join(re.escape(t) for t in sorted(tokens, key=len, reverse=True))
    return tokens, re.compile(WORD.format(f'({names})')), regexes, literals


def current(text: str) -> str:
    """Return `text` as a build after the rename would have printed it (unchanged when it already is)."""
    tokens, token_rx, regexes, _ = _table()
    for rx, new in regexes:
        text = rx.sub(new, text)
    return token_rx.sub(lambda m: tokens[m.group(1)], text)


def spellings(literal: str) -> list[str]:
    """Return `literal` and, when the rename changed it, its spelling before."""
    tokens, _, _, literals = _table()
    older = literal
    for new, old in literals:
        older = older.replace(new, old)
    for old, new in tokens.items():
        if new in older:
            older = re.sub(WORD.format(re.escape(new)), old, older)
    return [literal] if older == literal else [literal, older]


def current_report(value: object) -> object:
    """Return a HW Test report (its JSON) with every key and string in today's names."""
    if isinstance(value, dict):
        return {current(k): current_report(v) for k, v in value.items()}
    if isinstance(value, list):
        return [current_report(v) for v in value]
    if isinstance(value, str):
        whole = {old: new for new, old in _table()[3]}
        return whole.get(value) or current(value)
    return value
