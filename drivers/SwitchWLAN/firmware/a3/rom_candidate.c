int switch_a3_rom_compatible(void)
{
    const uint32_t *guard = switch_a3_rom_guards;
    while (*guard) {
        const uint32_t address = *guard++;
        const volatile uint32_t *rom = (const volatile uint32_t *)(address & ~1u);
        for (uint32_t words = address & 1u ? 2u : 4u; words; --words) {
            const uint32_t actual = *rom++;
            const uint32_t expected = *guard++;
            if (actual != expected) {
#if DEVELOPMENT || DEBUG
                switch_a3_state.reserved[0] = (uint32_t)(uintptr_t)(rom - 1);
                switch_a3_state.reserved[1] = expected;
                switch_a3_state.reserved[2] = actual;
#endif
                return 0;
            }
        }
    }
    return 1;
}
