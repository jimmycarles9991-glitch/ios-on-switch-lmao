static inline int switch_wlan_rom_bounds(uint32_t rom_bytes, uint32_t ram_bytes)
{
    return rom_bytes && !(rom_bytes & 3) && ram_bytes > SWITCH_WLAN_ROM_DATA_OFFSET + 4 &&
           rom_bytes <= ram_bytes - SWITCH_WLAN_ROM_DATA_OFFSET - 4;
}

