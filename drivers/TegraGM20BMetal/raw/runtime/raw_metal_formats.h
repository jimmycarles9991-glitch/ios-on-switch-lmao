constexpr bool sortedByFormat()
{
    for (size_t i = 1; i < std::size(kDescribed); i++)
        if (kDescribed[i - 1].mtl >= kDescribed[i].mtl)
            return false;
    return true;
}

static_assert(sortedByFormat());

constexpr const Described *described(uint32_t mtl)
{
    size_t lo = 0, hi = std::size(kDescribed);
    while (lo < hi) {
        const size_t mid = (lo + hi) / 2;
        if (kDescribed[mid].mtl == mtl)
            return &kDescribed[mid];
        if (kDescribed[mid].mtl < mtl)
            lo = mid + 1;
        else
            hi = mid;
    }
    return nullptr;
}

// 0 for a format of blocks and for one Metal does not describe
constexpr uint32_t texelBytes(uint32_t mtl)
{
    const Described *d = described(mtl);
    return d && d->blockW == 1 && d->blockH == 1 ? d->bytes : 0;
}

// A linear texture's row of `width` texels of `bytes` each, rounded up to `align`; 0 when either is 0, as Metal answers a
// format with no linear form
constexpr uint64_t linearRow(uint64_t width, uint32_t bytes, uint64_t align)
{
    if (!bytes || !align)
        return 0;
    return (width * bytes + align - 1) / align * align;
}

