#!/usr/bin/env python3
"""Core Animation's generic merge states' selector table of an IPSW kind (precompile/ca-selectors/<build>.txt).

usage: ca_selectors.py <build>.txt <raw_ca_selector_layout.h>

The generic merge states (..Xghfc) read a FragmentShaderConfig from a fragment buffer: the table's layout line names
that buffer's slot, the config's length and its padding bytes, which no selector compares. Lines of a state's key and a
config's bytes in hex (its padding 0) list configs devices drew, which the raw pack compiles selector variants of.
The header gives the layout to the raw runtime (raw_ca_selectors.h).
"""

import re
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

MAX_LENGTH = 64  # raw_ca_selectors.h kCaSelectorMax
LAYOUT = re.compile(r'layout slot=(\d+) length=(\d+) padding=([0-9,-]*)$')
CONFIG = re.compile(r'([0-9a-f]{16}) ([0-9a-f]+)$')


@dataclass
class Selectors:
    slot: int
    length: int
    padding: set[int]
    configs: list[tuple[int, bytes]] = field(default_factory=list)

    def padding_mask(self) -> int:
        return sum(1 << i for i in self.padding)


def byte_set(text: str) -> set[int]:
    out = set()
    for part in filter(None, text.split(',')):
        first, _, last = part.partition('-')
        out |= set(range(int(first), int(last or first) + 1))
    return out


def parse(text: str) -> Selectors:
    selectors = None
    configs = []
    for n, raw_line in enumerate(text.splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith('#'):
            continue
        if m := LAYOUT.match(line):
            selectors = Selectors(int(m[1]), int(m[2]), byte_set(m[3]))
        elif m := CONFIG.match(line):
            configs.append((int(m[1], 16), bytes.fromhex(m[2])))
        else:
            raise ValueError(f'line {n}: neither a layout nor a "<key> <config hex>" line: {line}')
    if selectors is None:
        raise ValueError('no layout line')
    check(selectors, configs)
    selectors.configs = configs
    return selectors


def check(selectors: Selectors, configs: list[tuple[int, bytes]]) -> None:
    if not 0 < selectors.length <= MAX_LENGTH or max(selectors.padding, default=0) >= selectors.length:
        raise ValueError(f'a layout of {selectors.length} bytes, padding {sorted(selectors.padding)}')
    for key, config in configs:
        if len(config) != selectors.length:
            raise ValueError(f'{key:016x}: a config of {len(config)} bytes, the layout has {selectors.length}')
        if any(config[i] for i in selectors.padding):
            raise ValueError(f'{key:016x}: a config of padding bytes not 0 ({config.hex()})')
    if len(set(configs)) != len(configs):
        raise ValueError('a config listed twice')


def dispatch(selectors: Selectors) -> tuple[list[bytes], list[int], list[int]]:
    configs = sorted({value for _, value in selectors.configs})
    bits, keys = [], [0] * len(configs)
    candidates = [i for i in range(8 * selectors.length) if i // 8 not in selectors.padding]
    while len(set(keys)) < len(configs):

        def divided(bit: int, current: list[int]) -> list[int]:
            return [key * 2 + (value[bit // 8] >> (bit % 8) & 1) for key, value in zip(current, configs, strict=True)]

        bit = min(candidates, key=lambda b: (sum(n * n for n in Counter(divided(b, keys)).values()), b))
        keys = divided(bit, keys)
        bits.append(bit)
        candidates.remove(bit)
    slots = [0] * (1 << len(bits))
    for index, key in enumerate(keys, 1):
        slots[key] = index
    return configs, bits, slots


def selector_id(selectors: Selectors, value: bytes) -> int:
    if len(value) < selectors.length:
        return 0
    configs, bits, slots = dispatch(selectors)
    key = 0
    for bit in bits:
        key = key * 2 + (value[bit // 8] >> (bit % 8) & 1)
    index = slots[key]
    if not index or any(
        value[i] != configs[index - 1][i] for i in range(selectors.length) if i not in selectors.padding
    ):
        return 0
    return index


def header(selectors: Selectors, source: str) -> str:
    configs, bits, slots = dispatch(selectors)
    words = (selectors.length + 7) // 8
    masks = [
        sum(
            0xFF << (8 * (i % 8))
            for i in range(w * 8, min((w + 1) * 8, selectors.length))
            if i not in selectors.padding
        )
        for w in range(words)
    ]
    rows = []
    for value in configs:
        fields = [f'0x{int.from_bytes(value[w * 8 : (w + 1) * 8], "little"):x}ull' for w in range(words)]
        rows.append('    {' + ', '.join(fields) + '},')
    table = ['    ' + ', '.join(map(str, slots[i : i + 16])) + ',' for i in range(0, len(slots), 16)]
    key = (
        ' |\n        '.join(
            f'uint32_t((value[{bit // 64}] >> {bit % 64}) & 1) << {len(bits) - i - 1}' for i, bit in enumerate(bits)
        )
        or '0'
    )
    result = (
        f'// Generated by precompile/ca-selectors/ca_selectors.py from {source}\n'
        '#pragma once\n'
        '#include <cstddef>\n#include <cstdint>\n#include <cstring>\n\n'
        'namespace raw {\n\n'
        f'constexpr uint8_t kCaSelectorSlot = {selectors.slot}, kCaSelectorLength = {selectors.length};\n'
        f'constexpr uint64_t kCaSelectorPadding = 0x{selectors.padding_mask():x}ull;\n\n'
        f'constexpr uint16_t kCaSelectorConfigs = {len(configs)};\n'
    )
    if configs:
        result += (
            f'constexpr uint64_t kCaSelectorMasks[{words}] = {{'
            + ', '.join(f'0x{mask:x}ull' for mask in masks)
            + '};\n'
            f'constexpr uint64_t kCaSelectorValues[{len(configs)}][{words}] = {{\n' + '\n'.join(rows) + '\n};\n'
            f'constexpr uint16_t kCaSelectorIds[{len(slots)}] = {{\n' + '\n'.join(table) + '\n};\n\n'
        )
    result += 'inline uint16_t caSelectorId(const uint8_t *bytes, size_t size)\n{\n'
    if configs:
        result += (
            '    if (!bytes || size < kCaSelectorLength)\n        return 0;\n'
            f'    uint64_t value[{words}] = {{}};\n'
            '    memcpy(value, bytes, kCaSelectorLength);\n'
            f'    for (size_t i = 0; i < {words}; i++)\n        value[i] &= kCaSelectorMasks[i];\n'
            f'    const uint32_t key = {key};\n'
            '    const uint16_t id = kCaSelectorIds[key];\n'
            '    return id && !memcmp(value, kCaSelectorValues[id - 1], sizeof value) ? id : 0;\n'
        )
    else:
        result += '    (void)bytes;\n    (void)size;\n    return 0;\n'
    return result + '}\n\n}  // namespace raw\n'


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    table = Path(sys.argv[1])
    Path(sys.argv[2]).write_text(header(parse(table.read_text()), f'precompile/ca-selectors/{table.name}'))


if __name__ == '__main__':
    main()
